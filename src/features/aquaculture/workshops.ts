export function getWorkshop(id: string): WorkshopDefinition {
  const workshop = WORKSHOPS.find((item) => item.id === id);
  if (!workshop) throw new RangeError(`Unknown workshop: ${id}`);
  return workshop;
}

/** Return independent objects so refreshing a demo never shares mutable pool state. */
export function getWorkshopPools(workshopId: string): WorkshopPoolLayout[] {
  getWorkshop(workshopId);
  return POOL_RECTANGLES[workshopId].map(([deviceId, channel, row, position, x, y, width, height]) => ({
    id: `${deviceId}-${String(channel).padStart(2, '0')}`,
    deviceId, channel, row, position, x, y, width, height,
  }));
}
